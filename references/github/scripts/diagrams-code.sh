#!/usr/bin/env bash
# Diagramas de classes e de pacotes gerados do codigo com o pyreverse (pylint),
# gravados entre marcadores no docs/ARCHITECTURE.md. As pastas lidas sao as do
# coverage.businessLogicPaths do fuzkrigo.config.json, que sao o modelo de
# dominio. O diagrama e tao bom quanto as anotacoes de tipo: atributo sem tipo
# anotado nao vira relacao.
# Class and package diagrams generated from the code with pyreverse (pylint),
# written between markers in docs/ARCHITECTURE.md. The folders read are those
# of coverage.businessLogicPaths in fuzkrigo.config.json, which are the domain
# model. The diagram is only as good as the type annotations: an attribute
# without an annotated type does not become a relation.
#
# Uso, a partir da raiz do projeto / usage, from the project root:
#   bash .github/scripts/diagrams-code.sh generate   # grava os blocos (Portao 3) / writes the blocks (Gate 3)
#   bash .github/scripts/diagrams-code.sh check      # CI: reprova se o trecho nao bate / fails on mismatch
#
# Marcadores, um par por diagrama, cada um sozinho na linha:
# Markers, one pair per diagram, each alone on its line:
#   <!-- fuzkrigo:diagrama-classes:inicio -->   <!-- fuzkrigo:diagrama-classes:fim -->
#   <!-- fuzkrigo:diagrama-pacotes:inicio -->   <!-- fuzkrigo:diagrama-pacotes:fim -->
set -euo pipefail

source "$(dirname "${BASH_SOURCE[0]}")/coverage-config.sh"

ARCHITECTURE_FILE=docs/ARCHITECTURE.md

# Le o ARCHITECTURE.md, confere os marcadores e, com os .mmd do pyreverse,
# grava (generate) ou compara (check) o trecho entre eles. Fim de linha: a
# comparacao ignora CRLF/LF, porque o Windows grava CRLF e o CI le LF; a
# gravacao preserva o fim de linha que o arquivo ja usa. Modo "markers" so
# confere os marcadores, antes de rodar o pyreverse.
# Reads ARCHITECTURE.md, checks the markers and, with pyreverse's .mmd files,
# writes (generate) or compares (check) the text between them. Line endings:
# the comparison ignores CRLF/LF, because Windows writes CRLF and CI reads LF;
# writing keeps the line ending the file already uses. "markers" mode only
# checks the markers, before pyreverse runs.
DIAGRAMS_JS='
const fs = require("fs");
const [mode, file, dir] = process.argv.slice(1);
const NOTICE = "<!-- gerado por .github/scripts/diagrams-code.sh generate; nao editar a mao / " +
  "generated by .github/scripts/diagrams-code.sh generate; do not edit by hand -->";
const DIAGRAMS = [["diagrama-classes", "classes_codigo.mmd"], ["diagrama-pacotes", "packages_codigo.mmd"]];
const fail = (message) => { console.error(message); process.exit(1); };
const raw = fs.readFileSync(file, "utf-8");
const eol = raw.includes("\r\n") ? "\r\n" : "\n";
let lines = raw.replace(/\r\n/g, "\n").split("\n");
const stale = [];
for (const [name, mmdFile] of DIAGRAMS) {
  const start = "<!-- fuzkrigo:" + name + ":inicio -->";
  const end = "<!-- fuzkrigo:" + name + ":fim -->";
  const find = (marker) => lines.flatMap((line, index) => (line.trim() === marker ? [index] : []));
  const [starts, ends] = [find(start), find(end)];
  if (starts.length !== 1 || ends.length !== 1 || starts[0] > ends[0]) {
    fail("marcadores de " + name + " ausentes, repetidos ou fora de ordem no " + file +
      ": precisa de um " + start + " e, depois dele, um " + end +
      " — modelo na skill iniciar-projeto, references/architecture-md.md");
  }
  if (mode === "markers") continue;
  // Nada a desenhar: sem classe, o pyreverse grava so o cabecalho, e com um
  // modulo so (pasta so com __init__.py) nem grava o de pacotes (pylint
  // 4.1.3). O Mermaid recusa o diagrama vazio como erro de sintaxe (mermaid
  // 12.3.0), entao vai uma frase no lugar.
  // Nothing to draw: without classes, pyreverse writes only the header, and
  // with a single module (folder with only __init__.py) it does not even
  // write the package one (pylint 4.1.3). Mermaid rejects the empty diagram
  // as a syntax error (mermaid 12.3.0), so a sentence goes in its place.
  const mmdPath = dir + "/" + mmdFile;
  const diagram = fs.existsSync(mmdPath) ?
    fs.readFileSync(mmdPath, "utf-8").replace(/\r\n/g, "\n").trimEnd().split("\n") : [];
  const body = diagram.length > 1 ? ["```mermaid", ...diagram, "```"] :
    ["Diagrama vazio: nada a desenhar nas pastas do modelo de dominio ainda."];
  const block = [NOTICE, ...body];
  const current = lines.slice(starts[0] + 1, ends[0]);
  if (current.join("\n") !== block.join("\n")) {
    stale.push(name);
    lines.splice(starts[0] + 1, ends[0] - starts[0] - 1, ...block);
  }
}
if (mode === "check" && stale.length > 0) {
  fail("diagramas desatualizados no " + file + ": " + stale.join(", ") +
    " — rode \"bash .github/scripts/diagrams-code.sh generate\" e commite o resultado; se ja rodou," +
    " confira se o pylint local tem a versao impressa acima");
}
if (mode === "generate" && stale.length > 0) fs.writeFileSync(file, lines.join(eol));
if (mode !== "markers") {
  console.log(mode === "check" ? "diagramas do codigo conferidos" :
    stale.length > 0 ? "diagramas gravados no " + file + ": " + stale.join(", ") : "diagramas ja atualizados");
}
'

mode=${1:-}
if [ "$mode" != generate ] && [ "$mode" != check ]; then
  echo "uso: bash .github/scripts/diagrams-code.sh generate|check" >&2
  exit 1
fi

if [ ! -f "$COVERAGE_CONFIG_FILE" ]; then
  echo "sem $COVERAGE_CONFIG_FILE — diagramas nao conferidos"
  exit 0
fi
if [ ! -f "$ARCHITECTURE_FILE" ]; then
  echo "aviso: sem $ARCHITECTURE_FILE (etapa A2 ainda nao feita, ou experimento) — diagramas nao conferidos"
  exit 0
fi

node -e "$DIAGRAMS_JS" markers "$ARCHITECTURE_FILE" || exit 1
read_coverage_config

# Cada padrao "pasta/**" vira a pasta. O pyreverse so le pacote regular: sem
# __init__.py, ou com erro de sintaxe, ele sai 0 com o diagrama vazio
# (testado no pylint 4.1.3), entao essas falhas sao barradas aqui e no log.
# Each "folder/**" pattern becomes the folder. pyreverse only reads regular
# packages: without __init__.py, or with a syntax error, it exits 0 with an
# empty diagram (tested on pylint 4.1.3), so those failures are stopped here
# and in the log.
folders=()
IFS=, read -ra patterns <<< "$COVERAGE_INCLUDE"
for pattern in "${patterns[@]}"; do
  folder=${pattern%"/**"}
  if [ "$folder" = "$pattern" ] || [ -z "$folder" ]; then
    echo "padrao '$pattern' do coverage.businessLogicPaths nao termina em /** — os diagramas precisam da pasta do modelo de dominio (ex.: src/dominio/**)" >&2
    exit 1
  fi
  if [ ! -d "$folder" ]; then
    echo "pasta '$folder' do coverage.businessLogicPaths nao existe" >&2
    exit 1
  fi
  if [ ! -f "$folder/__init__.py" ]; then
    echo "pasta '$folder' sem __init__.py — o pyreverse so le pacote regular e geraria um diagrama vazio" >&2
    exit 1
  fi
  folders+=("$folder")
done

# Na maquina, o pyreverse vem do pylint das dependencias de desenvolvimento do
# projeto. No CI (CI=true no GitHub Actions), o script o instala sem versao
# fixa, como o mutmut, quando o projeto nao o trouxe.
# On the machine, pyreverse comes from the pylint in the project's development
# dependencies. In CI (CI=true on GitHub Actions), the script installs it,
# unpinned like mutmut, when the project did not bring it.
if ! command -v pyreverse >/dev/null 2>&1; then
  if [ "${CI:-}" = true ]; then
    python -m pip install pylint
  else
    echo "pyreverse nao encontrado — adicione pylint as dependencias de desenvolvimento do projeto e ative o ambiente virtual antes de rodar" >&2
    exit 1
  fi
fi
pyreverse --version

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Com __init__.py na pasta, o caminho a partir da raiz basta: no pylint 4.1.3,
# "src/dominio" deu o mesmo diagrama que --source-roots src e que rodar de
# dentro de src. Mensagens de falha que ele imprime e mesmo assim sai 0
# reprovam aqui.
# With __init__.py in the folder, the path from the root is enough: on pylint
# 4.1.3, "src/dominio" gave the same diagram as --source-roots src and as
# running from inside src. Failure messages it prints while still exiting 0
# fail here.
if ! pyreverse -o mmd -p codigo -d "$work" "${folders[@]}" > "$work/pyreverse.log" 2>&1; then
  cat "$work/pyreverse.log" >&2
  exit 1
fi
if grep -qE "Failed to import module|Parsing Python code failed" "$work/pyreverse.log"; then
  cat "$work/pyreverse.log" >&2
  echo "o pyreverse nao conseguiu ler todo o codigo das pastas ${folders[*]} — corrija antes de gerar os diagramas" >&2
  exit 1
fi

node -e "$DIAGRAMS_JS" "$mode" "$ARCHITECTURE_FILE" "$work" || exit 1
